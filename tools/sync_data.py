def youtube():
    key = os.environ.get("YOUTUBE_API_KEY", "")
    videos = youtube_api(key) if key else youtube_feed()
    # a changing ?t= asks YouTube's servers for a fresh copy: right after a thumbnail
    # is changed, the plain address can keep handing out the old one for hours
    fresh = int(time.time())
    cards = []
    for v in videos:
        cover = save_cover("video", f"youtube-{v['id']}.jpg", [f"https://i.ytimg.com/vi/{v['id']}/maxresdefault.jpg?t={fresh}",
                                                                   f"https://i.ytimg.com/vi/{v['id']}/mqdefault.jpg?t={fresh}"])
        cards.append({
            "source": "youtube", "id": v["id"],
            "when": v["published"] or "",
            "date": month(v["published"]),
            "title": v["title"],
            "desc": first_line(v["description"]),
            "tags": ["youtube"],
            "url": "https://www.youtube.com/watch?v=" + v["id"],
            "cover": cover,
            "count": int(v["views"] or 0),
            "archive": False,
        })
    return cards, {"note": "" if key else "no API key: read from the public feed (newest 15 videos)"}


def youtube_api(key):
    api = "https://www.googleapis.com/youtube/v3/"
    channel = fetch_json(f"{api}channels?part=contentDetails&id={YOUTUBE_CHANNEL}&key={key}")
    uploads = channel["items"][0]["contentDetails"]["relatedPlaylists"]["uploads"]
    ids, token = [], ""
    while True:
        page = fetch_json(f"{api}playlistItems?part=contentDetails&maxResults=50&playlistId={uploads}"
                          f"&key={key}" + (f"&pageToken={token}" if token else ""))
        ids += [item["contentDetails"]["videoId"] for item in page.get("items", [])]
        token = page.get("nextPageToken", "")
        if not token:
            break
    videos = []
    for start in range(0, len(ids), 50):
        chunk = ",".join(ids[start:start + 50])
        for item in fetch_json(f"{api}videos?part=snippet,statistics&id={chunk}&key={key}").get("items", []):
            videos.append({
                "id": item["id"],
                "title": item["snippet"]["title"],
                "published": item["snippet"]["publishedAt"],
                "description": item["snippet"].get("description", ""),
                "views": item.get("statistics", {}).get("viewCount", 0),
            })
    return videos


def youtube_feed():
    ns = {"a": "http://www.w3.org/2005/Atom", "yt": "http://www.youtube.com/xml/schemas/2015",
          "m": "http://search.yahoo.com/mrss/"}
    feed = ET.fromstring(fetch("https://www.youtube.com/feeds/videos.xml?channel_id=" + YOUTUBE_CHANNEL))
    videos = []
    for entry in feed.findall("a:entry", ns):
        stats = entry.find("m:group/m:community/m:statistics", ns)
        text = entry.find("m:group/m:description", ns)
        videos.append({
            "id": entry.find("yt:videoId", ns).text,
            "title": entry.find("a:title", ns).text or "",
            "published": entry.find("a:published", ns).text or "",
            "description": (text.text or "") if text is not None else "",
            "views": stats.get("views", 0) if stats is not None else 0,
        })
    return videos


