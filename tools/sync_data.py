#!/usr/bin/env python3
"""tools/sync_data.py — pull my real works and their numbers into the site.

Once a day a GitHub Action (.github/workflows/sync-counts.yml) runs this.
It asks each of my four accounts what I have published and how it is doing,
and writes the answer into files the site reads as plain scripts:

    cards/live.js        every repo / video / artwork as a card, with its number
    cards/history.json   one line per day: the totals, so growth can be shown later
    cards/<stream>/images/live/   small cover pictures for videos and artworks

Where each number comes from:

    GitHub     public API, no key needed          stars per repository
    YouTube    Data API with YOUTUBE_API_KEY,     views per video
               or the channel's public feed when there is no key (newest 15 only)
    Bilibili   public web API, no key             views per video
    Pixiv      app API with PIXIV_REFRESH_TOKEN   bookmarks per artwork
               (skipped when there is no token)

If one account cannot be reached, its cards are kept exactly as they were
on the last good run, so a bad day never turns a number into zero. If no
account can be reached at all, nothing is written and the run fails.

Run it by hand from the repo folder:

    python3 tools/sync_data.py

The two keys are read from the environment, or from a .env file next to
this repo's index.html (never committed). Set SYNC_NO_ENV=1 to ignore .env.
"""

