# Pixiv — every artwork on my account (needs the refresh token)
# ---------------------------------------------------------------------------
def pixiv():
    token = os.environ.get("PIXIV_REFRESH_TOKEN", "")
    if not token:
        raise Skip("no PIXIV_REFRESH_TOKEN")
    from pixivpy3 import AppPixivAPI                    # pip install pixivpy3
    api = AppPixivAPI()
    api.auth(refresh_token=token)

    def read(thing, name, default=None):
        """pixivpy3 hands back plain dictionaries today and typed objects in its next version: read either."""
        value = thing.get(name) if isinstance(thing, dict) else getattr(thing, name, None)
        return default if value is None else value

    works = []
    for kind in ("illust", "manga"):                    # Pixiv files multi-page comics separately
        query = {"user_id": int(PIXIV_USER), "type": kind}
        for _ in range(30):                             # 30 pages of 30 = 900 works, plenty
            page = api.user_illusts(**query)
            if read(page, "error"):
                raise RuntimeError(str(read(page, "error"))[:200])
            works += list(read(page, "illusts", []))
            if not read(page, "next_url"):
                break
            query = api.parse_qs(read(page, "next_url"))

    cards = []
    for work in works:
        number = str(read(work, "id"))
        picture = read(read(work, "image_urls", {}), "large", "")
        picture = re.sub(r"/c/[^/]+/img-master/", "/img-master/", picture)   # the 1200px JPEG, not a 600px (sometimes WebP) copy
        cover = save_cover("art", f"pixiv-{number}.jpg", picture,
                           {"Referer": "https://app-api.pixiv.net/"}) if picture else ""
        tags = [read(t, "translated_name") or read(t, "name", "") for t in read(work, "tags", [])]
        cards.append({
            "source": "pixiv", "id": number,
            "when": read(work, "create_date", ""),
            "date": month(read(work, "create_date", "")),
            "title": read(work, "title", ""),
            "desc": first_line(caption_text(read(work, "caption", ""))),
            "tags": [t.lower() for t in tags if t][:3],
            "url": f"https://www.pixiv.net/artworks/{number}",
            "cover": cover,
            "count": int(read(work, "total_bookmarks", 0)),
            "archive": False,
        })
    return cards, {}


class Skip(Exception):
    """An account that was not asked at all (no key). Not a failure."""


# ---------------------------------------------------------------------------
def read_previous():
    """What the last run wrote, so a failed account can keep its cards."""
    if not OUT.exists():
        return {}
    text = OUT.read_text(encoding="utf-8")
    try:
        return json.loads(text[text.index("window.LIVE = ") + len("window.LIVE = "):].rstrip().rstrip(";"))
    except Exception as error:
        print(f"could not read the previous {OUT.name}: {error}")
        return {}


def main():
    load_env(ROOT / ".env")
    previous = read_previous()
    old_cards = [c for stream in ("cs", "art", "video") for c in previous.get(stream, [])]
    old_sources = previous.get("sources", {})
    now = datetime.now(timezone.utc)
    stamp = now.strftime("%Y-%m-%dT%H:%M:%SZ")

    jobs = [("github", "cs", github), ("youtube", "video", youtube),
            ("bilibili", "video", lambda: bilibili(old_cards)), ("pixiv", "art", pixiv)]
    streams = {"cs": [], "art": [], "video": []}
    sources, reached = {}, 0
    for name, stream, job in jobs:
        kept = [c for c in old_cards if c.get("source") == name]
        try:
            cards, extra = job()
            reached += 1
            sources[name] = {"ok": True, "checked": stamp, "works": len(cards), **extra}
            print(f"  {name}: {len(cards)} works, {sum(c['count'] for c in cards)} in total"
                  + (f" — {extra['note']}" if extra.get("note") else ""))
        except Skip as skip:
            cards = kept
            sources[name] = {**old_sources.get(name, {}), "ok": bool(old_sources.get(name, {}).get("ok")),
                             "works": len(cards), "note": f"skipped: {skip}"}
            print(f"  {name}: skipped ({skip}); kept {len(cards)} from before")
        except Exception as error:
            cards = kept
            sources[name] = {**old_sources.get(name, {}), "ok": False, "works": len(cards),
                             "note": f"not reached {stamp}: {str(error)[:160]}"}
            print(f"  {name}: FAILED ({error}); kept {len(cards)} from before")
        streams[stream] += cards

    if not reached:
        print("no account could be reached; nothing written")
        return 1

    for cards in streams.values():
        cards.sort(key=lambda c: (moment(c.get("when") or c["date"]), c["title"].lower()), reverse=True)   # newest first, to the second

    live = {"updated": stamp, "sources": sources, **streams}
    OUT.write_text(HEADER + json.dumps(live, indent=2, ensure_ascii=False) + ";\n", encoding="utf-8")

    # one line per day, so growth over time can be drawn later
    total = lambda name: sum(c["count"] for s in streams.values() for c in s if c["source"] == name)
    today = {
        "date": now.strftime("%Y-%m-%d"),
        "stars": total("github"),
        "views": total("youtube") + total("bilibili"),
        "likes": total("pixiv"),
        "github_stars": total("github"), "youtube_views": total("youtube"),
        "bilibili_views": total("bilibili"), "pixiv_bookmarks": total("pixiv"),
        "bilibili_followers": sources.get("bilibili", {}).get("followers"),
        "works": {name: len(cards) for name, cards in streams.items()},
    }
    days = []
    if HISTORY.exists():
        try:
            days = json.loads(HISTORY.read_text(encoding="utf-8")).get("days", [])
        except Exception as error:
            print(f"could not read {HISTORY.name}, starting it again: {error}")
    days = [d for d in days if d.get("date") != today["date"]] + [today]
    days.sort(key=lambda d: d["date"])
    HISTORY.write_text(json.dumps({"days": days}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{len(c)} {n}" for n, c in streams.items())
          + f" | {HISTORY.relative_to(ROOT)}: {len(days)} day(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
