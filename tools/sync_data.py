def is_course(repo):
    """Course notes, not a project: tagged course/courses/learning on GitHub, or described as coursework."""
    topics = {t.lower() for t in (repo.get("topics") or [])}
    return bool(topics & {"course", "courses", "learning"}) or \
        (repo.get("description") or "").lower().startswith("personal notes and coursework")


def github():
    headers = {"Accept": "application/vnd.github+json"}
    token = os.environ.get("GITHUB_TOKEN", "")
    if token:
        headers["Authorization"] = "Bearer " + token
    repos, page = [], 1
    while True:
        batch = fetch_json(f"https://api.github.com/users/{GITHUB_USER}/repos"
                           f"?type=owner&sort=created&per_page=100&page={page}", headers)
        repos += batch
        if len(batch) < 100:
            break
        page += 1
    cards = []
    for repo in repos:
        if repo.get("fork") or repo.get("private") or repo["name"] in GITHUB_HIDE:
            continue
        tags = [t for t in [repo.get("language")] + list(repo.get("topics") or []) if t]
        cards.append({
            "source": "github", "id": repo["name"],
            "group": "courses" if is_course(repo) else "projects",
            "when": repo.get("created_at") or "",
            "date": month(repo.get("created_at")),
            "title": repo["name"],
            "desc": first_line(repo.get("description")),
            "tags": [t.lower() for t in tags[:3]],
            "url": repo["html_url"],
            "cover": "",
            "count": int(repo.get("stargazers_count") or 0),
            "archive": bool(repo.get("archived")),
        })
    return cards, {}


