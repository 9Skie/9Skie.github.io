def load_env(path):
    """Local runs: read KEY=value lines from .env without printing them."""
    if os.environ.get("SYNC_NO_ENV") or not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def fetch(url, headers=None, opener=None, tries=3):
    """GET a URL and return its bytes. Retries a couple of times on a hiccup."""
    request = urllib.request.Request(url, headers={"User-Agent": UA, **(headers or {})})
    last = None
    for attempt in range(tries):
        try:
            with (opener.open if opener else urllib.request.urlopen)(request, timeout=25) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            last = error
            if error.code in (401, 403, 404, 412):      # asking again will not help
                break
        except Exception as error:                      # timeouts, resets
            last = error
        time.sleep(1.5 * (attempt + 1))
    raise last


def fetch_json(url, headers=None, opener=None):
    return json.loads(fetch(url, headers, opener).decode("utf-8", "replace"))


def month(text):
    """'2026-03-21T…' -> '2026-03' (what the cards show as their date)."""
    return (text or "")[:7]


def moment(text):
    """Any of the accounts' date formats -> seconds, so uploads minutes apart keep their order."""
    try:
        return datetime.fromisoformat((text or "").replace("Z", "+00:00")).timestamp()
    except ValueError:
        return 0.0


def first_line(text, limit=110):
    """A one-line description out of a longer one."""
    for line in (text or "").splitlines():
        line = " ".join(line.split())
        if line:
            return line if len(line) <= limit else line[: limit - 1].rstrip() + "…"
    return ""


def caption_text(caption):
    """Pixiv captions are HTML: line breaks become real ones, other tags just go."""
    text = re.sub(r"<br\s*/?>", "\n", caption or "", flags=re.I)
    return html.unescape(re.sub(r"<[^>]+>", "", text))


def save_cover(stream, name, url, headers=None, opener=None):
    """Download a cover picture (sharp at card size on 2x screens); return its path as the site uses it.

    Every run fetches the cover again, so a thumbnail changed on the platform
    reaches the site on the next run. The file is rewritten only when the
    picture actually changed, and if the download fails the saved one is kept.
    The path ends in ?v=<code made from the picture>, so browsers fetch a new
    picture instead of showing the one they remember under the same name.
    """
    folder = COVERS[stream]
    target = folder / name
    data = b""
    for choice in ([url] if isinstance(url, str) else url):   # biggest first, smaller if missing
        try:
            data = fetch(choice, headers, opener)
        except Exception:
            continue
        if len(data) >= 2000:                           # a real picture, not an error page
            break
    if len(data) >= 2000:
        if not target.exists() or target.read_bytes() != data:
            folder.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            print(f"    cover saved: {name}")
    elif target.exists():
        print(f"    cover for {name} not reached; keeping the saved one")
    else:
        print(f"    cover for {name} not saved")
        return ""
    code = hashlib.sha1(target.read_bytes()).hexdigest()[:8]
    return f"{target.relative_to(ROOT).as_posix()}?v={code}"


