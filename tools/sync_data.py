# Bilibili — every video on my space
# ---------------------------------------------------------------------------
def bilibili(previous):
    jar = http.cookiejar.CookieJar()
    opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(jar))
    headers = {"Referer": f"https://space.bilibili.com/{BILIBILI_MID}/", "Origin": "https://space.bilibili.com",
               "Accept": "application/json, text/plain, */*", "Accept-Language": "zh-CN,zh;q=0.9,en;q=0.8"}

    # Bilibili turns away visitors with no cookie at all; this hands out an anonymous one
    try:
        visitor = fetch_json("https://api.bilibili.com/x/frontend/finger/spi", headers, opener)["data"]
        for name, value in (("buvid3", visitor["b_3"]), ("buvid4", visitor["b_4"])):
            jar.set_cookie(http.cookiejar.Cookie(0, name, value, None, False, ".bilibili.com", True, True, "/",
                                                 True, False, None, False, None, None, {}))
    except Exception as error:
        print(f"    no visitor cookie ({error}); trying without")

    extra = {}
    try:
        card = fetch_json(f"https://api.bilibili.com/x/web-interface/card?mid={BILIBILI_MID}", headers, opener)
        extra["followers"] = int((card.get("data") or {}).get("follower") or 0)
    except Exception as error:
        print(f"    follower count not read: {error}")

    videos, note = [], ""
    try:
        last = ""
        for _ in range(20):                             # 20 pages of 20 = 400 videos, plenty
            page = fetch_json("https://api.bilibili.com/x/v2/medialist/resource/list?type=1&otype=2"
                              f"&biz_id={BILIBILI_MID}&bvid=&with_current={'false' if last else 'true'}&mobi_app=web&ps=20"
                              f"&direction=false&sort_field=1&tid=0&desc=true" + (f"&oid={last}" if last else ""),
                              headers, opener)
            if page.get("code") != 0:
                raise RuntimeError(f"code {page.get('code')} {page.get('message')}")
            data = page.get("data") or {}
            batch = data.get("media_list") or []
            for item in batch:
                videos.append({"bvid": item["bv_id"], "title": item.get("title") or "", "intro": item.get("intro") or "",
                               "pubtime": int(item.get("pubtime") or 0), "cover": item.get("cover") or "",
                               "views": int((item.get("cnt_info") or {}).get("play") or 0)})
            if not batch or not data.get("has_more"):
                break
            last = batch[-1]["id"]
    except Exception as error:
        # the list is the fragile part; the per-video page is sturdier. Keep the videos
        # known from the last good run and just refresh their numbers.
        known = [c for c in previous if c.get("source") == "bilibili"]
        if not known:
            raise
        cards, refreshed = [], 0
        for old in known:
            new = dict(old)
            try:
                view = fetch_json(f"https://api.bilibili.com/x/web-interface/view?bvid={old['id']}", headers, opener)
                new["count"] = int(view["data"]["stat"]["view"])
                refreshed += 1
            except Exception as inner:
                print(f"    {old['id']}: kept the old number ({inner})")
            cards.append(new)
        if not refreshed:                               # Bilibili did not answer at all: that is a failed day
            raise RuntimeError(f"video list not readable ({error}) and no video page answered")
        note = f"video list not readable ({error}); refreshed {refreshed} of the {len(known)} known videos"
        return cards, {**extra, "note": note}

    cards = []
    for v in videos:
        cover = ""
        if v["cover"]:
            picture = v["cover"].replace("http://", "https://") + "@960w_540h_1c.jpg"
            cover = save_cover("video", f"bilibili-{v['bvid']}.jpg", picture, headers, opener)
        cards.append({
            "source": "bilibili", "id": v["bvid"],
            "when": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(v["pubtime"])),
            "date": time.strftime("%Y-%m", time.gmtime(v["pubtime"] + 8 * 3600)),   # Bilibili keeps China time
            "title": v["title"],
            "desc": first_line(v["intro"]),
            "tags": ["bilibili"],
            "url": "https://www.bilibili.com/video/" + v["bvid"],
            "cover": cover,
            "count": v["views"],
            "archive": False,
        })
    return cards, {**extra, "note": note}


